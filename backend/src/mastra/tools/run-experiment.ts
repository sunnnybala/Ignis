import { createTool } from '@mastra/core/tools';
import { z } from 'zod';
import { fetch } from 'undici';
import { logger } from '../../utils/logger';

// Read env var at runtime to allow test mocking
function getModalRunnerSyncUrl(): string {
  return (process.env.MODAL_RUNNER_SYNC_URL || '').trim();
}

// Error classification for smart retry decisions
type ErrorType =
  | 'none'
  | 'dataset_download'
  | 'import_error'
  | 'file_not_found'
  | 'runtime_error'
  | 'memory_error'
  | 'timeout';

export function classifyError(
  stderr: string,
  stdout: string,
  exitCode: number
): { type: ErrorType; retryable: boolean } {
  if (exitCode === 0) return { type: 'none', retryable: false };

  const combined = `${stderr}\n${stdout}`.toLowerCase();

  if (combined.includes('modulenotfounderror') || combined.includes('no module named')) {
    return { type: 'import_error', retryable: true };
  }
  if (combined.includes('filenotfounderror') || combined.includes('no such file')) {
    return { type: 'file_not_found', retryable: true };
  }
  if (combined.includes('out of memory') || combined.includes('oom')) {
    return { type: 'memory_error', retryable: true }; // Can suggest smaller batch size
  }
  if (combined.includes('timeout') || combined.includes('timed out')) {
    return { type: 'timeout', retryable: true };
  }
  if (combined.includes('kaggle') && combined.includes('download')) {
    return { type: 'dataset_download', retryable: false }; // Dataset issues need manual fix
  }

  return { type: 'runtime_error', retryable: true };
}

export function generateSuggestion(classification: { type: ErrorType; retryable: boolean }, stderr: string): string | undefined {
  if (!classification.retryable) {
    return undefined;
  }

  if (classification.type === 'import_error') {
    const match = stderr.match(/no module named ['"]?(\w+)/i);
    return match
      ? `Add '${match[1]}' to requirements.txt`
      : 'Check requirements.txt for missing packages';
  }
  if (classification.type === 'file_not_found') {
    return 'Check file paths against VERIFIED DATASET FILES. Print os.listdir() to see actual structure.';
  }
  if (classification.type === 'memory_error') {
    return 'Reduce batch_size or use gradient checkpointing';
  }
  if (classification.type === 'timeout') {
    return 'Reduce number of epochs or training data size';
  }

  return undefined;
}

export const runExperimentTool = createTool({
  id: 'run_experiment',
  description:
    'Execute experiment.py on Modal cloud and return results. ' +
    'Call this AFTER generating code to verify it works. ' +
    'If execution fails with a retryable error, fix the code and call again (max 3 attempts).',
  inputSchema: z.object({
    experimentPy: z.string().min(1).describe('The Python experiment code'),
    requirementsTxt: z.string().describe('Package requirements (one per line, no versions)'),
    datasetSlug: z.string().regex(/^[^/]+\/[^/]+$/).describe('Kaggle dataset slug (owner/dataset)'),
    datasetSubdir: z.string().optional().describe('Subdirectory within dataset'),
    attemptNumber: z.number().min(1).max(3).optional().describe('Current attempt (1-3)'),
  }),
  outputSchema: z.object({
    success: z.boolean(),
    exitCode: z.number(),
    stdout: z.string(),
    stderr: z.string(),
    errorType: z
      .enum(['none', 'dataset_download', 'import_error', 'file_not_found', 'runtime_error', 'memory_error', 'timeout'])
      .describe('Classified error type'),
    retryable: z.boolean().describe('Whether the error can be fixed by modifying code'),
    suggestion: z.string().optional().describe('Suggestion for fixing the error'),
    artifacts: z
      .array(
        z.object({
          name: z.string(),
          type: z.enum(['image', 'csv']),
        })
      )
      .optional()
      .describe('Output files generated by the experiment'),
  }),
  execute: async (input, toolContext) => {
    const requestContext = toolContext?.requestContext;
    const traceId = (requestContext as any)?.get?.('traceId') || crypto.randomUUID();
    const projectId = (requestContext as any)?.get?.('projectId');
    const attempt = input.attemptNumber || 1;

    // Detailed logging for debugging and test verification
    logger.info('tool.run_experiment.start', {
      traceId,
      projectId,
      attempt,
      datasetSlug: input.datasetSlug,
      datasetSubdir: input.datasetSubdir || '(none)',
      experimentPyLength: input.experimentPy.length,
      requirementsTxtLength: input.requirementsTxt.length,
      requirementsPreview: input.requirementsTxt.slice(0, 200),
    });

    // Log code snippet for debugging
    logger.debug('tool.run_experiment.code_preview', {
      traceId,
      first500Chars: input.experimentPy.slice(0, 500),
    });

    const modalRunnerSyncUrl = getModalRunnerSyncUrl();
    if (!modalRunnerSyncUrl) {
      return {
        success: false,
        exitCode: 1,
        stdout: '',
        stderr: 'MODAL_RUNNER_SYNC_URL not configured',
        errorType: 'runtime_error' as const,
        retryable: false,
      };
    }

    // Build dataset config for Modal sync endpoint
    const datasetJson = JSON.stringify({
      source: 'kaggle',
      kaggle: {
        dataset: input.datasetSlug,
        unzip: true,
      },
      layout: {
        subdir: input.datasetSubdir || '',
      },
    });

    // Sync endpoint payload (simplified - no callbacks needed)
    const payload = {
      traceId,
      experimentPy: input.experimentPy,
      requirementsTxt: input.requirementsTxt,
      datasetJson,
    };

    try {
      const resp = await fetch(modalRunnerSyncUrl, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
      });

      if (!resp.ok) {
        const body = await resp.text().catch(() => '');
        logger.warn('tool.run_experiment.modal_error', { traceId, status: resp.status, body: body.slice(0, 500) });
        return {
          success: false,
          exitCode: 1,
          stdout: '',
          stderr: `Modal runner error: HTTP ${resp.status}\n${body.slice(0, 1000)}`,
          errorType: 'runtime_error' as const,
          retryable: false,
        };
      }

      // Parse Modal response (contains results directly for sync execution)
      const result = (await resp.json()) as {
        exitCode: number;
        stdout?: string;
        stderr?: string;
        artifacts?: Array<{ name: string; type: string }>;
      };

      const stdout = result.stdout || '';
      const stderr = result.stderr || '';
      const exitCode = result.exitCode ?? 1;

      const classification = classifyError(stderr, stdout, exitCode);
      const suggestion = generateSuggestion(classification, stderr);

      const artifacts = result.artifacts?.map((a) => ({
        name: a.name,
        type: (a.type === 'csv' ? 'csv' : 'image') as 'image' | 'csv',
      }));

      logger.info('tool.run_experiment.complete', {
        traceId,
        success: exitCode === 0,
        exitCode,
        errorType: classification.type,
        retryable: classification.retryable,
        suggestion,
        attempt,
        stdoutLength: stdout.length,
        stderrLength: stderr.length,
        artifactsCount: artifacts?.length || 0,
      });

      // Log output previews for debugging
      if (stderr) {
        logger.debug('tool.run_experiment.stderr_preview', {
          traceId,
          preview: stderr.slice(0, 1000),
        });
      }
      if (stdout) {
        logger.debug('tool.run_experiment.stdout_preview', {
          traceId,
          preview: stdout.slice(0, 1000),
        });
      }

      return {
        success: exitCode === 0,
        exitCode,
        stdout: stdout.slice(0, 50000), // Truncate for context limits
        stderr: stderr.slice(0, 50000),
        errorType: classification.type,
        retryable: classification.retryable,
        suggestion,
        artifacts,
      };
    } catch (err) {
      const message = err instanceof Error ? err.message : 'Unknown error';
      logger.error('tool.run_experiment.exception', { traceId, error: message });
      return {
        success: false,
        exitCode: 1,
        stdout: '',
        stderr: `Tool execution error: ${message}`,
        errorType: 'runtime_error' as const,
        retryable: false,
      };
    }
  },
});
